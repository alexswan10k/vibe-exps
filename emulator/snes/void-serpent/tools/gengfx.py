#!/usr/bin/env python3
"""Generate SNES sprite tiles + palettes for Void Serpent.

The art source of truth is the ASCII tiles defined below. Running this writes:

    src/gfx.h        tile-index #defines (the sprite bytes are NOT C arrays)
    src/gfx/*.bin    one blob per upload unit, .incbin'd by data.asm

Both outputs are gitignored and regenerated by build.sh, so never commit them.

IMPORTANT -- why .bin instead of a C array: the devkitsnes linker discards
main.obj's ".data" section, so an initialised `u8 spr_gfx[] = {...}` builds
cleanly, reports success, and never reaches the ROM. The graphics then appear
as zero-filled (invisible) sprites at runtime. See CAVEATS.md section 3.

Run:  python3 tools/gengfx.py [--preview]
"""

import os
import sys

TILE = 8          # 8x8 tiles
TILE_BYTES = 32   # 4bpp: 8 rows * 4 bitplanes


# ---------------------------------------------------------------------------
# Palette definitions. Index 0 of a sprite palette is always transparent.
# ---------------------------------------------------------------------------


def rgb5(r, g, b):
    """Same encoding as PVSnesLib's RGB5 macro: r | g<<5 | b<<10."""
    return (r & 31) | ((g & 31) << 5) | ((b & 31) << 10)


def palette(colors):
    """Expand a list of RGB5 ints into little-endian CGRAM byte order."""
    out = []
    for c in colors:
        out.append(c & 0xFF)
        out.append((c >> 8) & 0xFF)
    while len(out) < 32:              # pad to a full 16-colour sprite palette
        out += [0, 0]
    return out


