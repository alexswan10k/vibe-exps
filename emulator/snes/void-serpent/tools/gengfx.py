def build():
    """Return the packed sprite tile stream and the TID_* offsets."""
    # Sprite order matters: the tile *offsets* below are derived from this list.
    # SPR_TAIL art points down, so it is rotated the same way as the head.
    spr_tiles = [
        SPR_BODY,
        SPR_TAIL,                                  # 1  tail, points DOWN
        rot90(SPR_TAIL),                           # 2  tail, points LEFT
        rot90(rot90(SPR_TAIL)),                    # 3  tail, points UP
        rot90(rot90(rot90(SPR_TAIL))),             # 4  tail, points RIGHT
        SPR_HEAD,                                  # 5  head, faces RIGHT
        rot90(SPR_HEAD),                           # 6  head, faces DOWN
        rot90(rot90(SPR_HEAD)),                    # 7  head, faces LEFT
        rot90(rot90(rot90(SPR_HEAD))),             # 8  head, faces UP
        SPR_FOOD_A, SPR_FOOD_B,
        SPR_BONUS_A, SPR_BONUS_B,
        SPR_SHARD_A, SPR_SHARD_B,
        SPR_FX_R1, SPR_FX_R2, SPR_FX_R3, SPR_FX_R4,
        SPR_GATE, SPR_GATE_CORE,
    ]

    spr_data = []
    for t in spr_tiles:
        spr_data += to_tile(t, SPR_CHARS)

    # Self-check: decode every tile back and compare with the source art.
    # This is what catches a bitplane/stride mismatch -- the failure mode is
    # silent (the ROM builds and sprites are simply wrong or invisible).
    for i, src_rows in enumerate(spr_tiles):
        got = decode_tile(spr_data, i)
        assert got == src_rows, (
            "tile %d does not round-trip:\n  expected %r\n  got      %r"
            % (i, src_rows, got))

    # Sprite tile numbers are in 8-byte units, and a 4bpp 8x8 sprite consumes
    # FOUR of them (32 bytes). So tile index N => unit offset N*4.
    order = ['BODY', 'TAIL_D', 'TAIL_L', 'TAIL_U', 'TAIL_R',
             'HEAD_R', 'HEAD_D', 'HEAD_L', 'HEAD_U',
             'FOOD_A', 'FOOD_B', 'BONUS_A', 'BONUS_B', 'SHARD_A', 'SHARD_B',
             'FX_R1', 'FX_R2', 'FX_R3', 'FX_R4', 'GATE', 'GATE_CORE']
    offs = {name: i * 4 for i, name in enumerate(order)}

    return spr_data, offs


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, os.pardir, 'src')
    gfxdir = os.path.join(src, 'gfx')
    header_path = os.path.join(src, 'gfx.h')

    if not os.path.isdir(gfxdir):
        os.makedirs(gfxdir)

    spr_data, offs = build()

    # One .bin per blob, assembled into ROM by data.asm.
    # (This wla-dx build's .incbin does not accept an offset/length pair, so
    # each blob gets its own file.)
    blobs = [('vsgfx_tiles', spr_data)]
    for name, data in (
        ('vpal_snake', PAL_SNAKE), ('vpal_food', PAL_FOOD), ('vpal_bonus', PAL_BONUS),
        ('vpal_shard', PAL_SHARD), ('vpal_fx', PAL_FX), ('vpal_portal', PAL_PORTAL),
    ):
        blobs.append((name, bytes(data)))

    for name, data in blobs:
        with open(os.path.join(gfxdir, name + '.bin'), 'wb') as f:
            f.write(bytes(data))

    if '--preview' in sys.argv:
        for name, data in blobs:
            print("  %-14s %4d bytes -> src/gfx/%s.bin" % (name, len(data), name))
        print("\nsprite tile indices, in 8-byte OAM tile units:")
        for k in sorted(offs, key=lambda k: offs[k]):
            print("  TID_%-14s unit %2d  (byte %d)" % (k, offs[k], offs[k] * 8))
        return

    lines = []
    lines.append('/* Generated by tools/gengfx.py -- do not edit by hand. */')
    lines.append('/* Run `python3 tools/gengfx.py` to regenerate. */')
    lines.append('')
    lines.append('#ifndef VSGFX_H')
    lines.append('#define VSGFX_H')
    lines.append('')
    lines.append('/* Tiles and palettes are NOT C arrays -- see tools/gengfx.py. They are')
    lines.append('   assembled into ROM by data.asm and uploaded with DMA. */')
    lines.append('#define VSGFX_TILES_SIZE %d' % len(spr_data))
    lines.append('#define VSGFX_PAL_SIZE   32')
    lines.append('')
    lines.append('/* Sprite tile indices, in 8-byte OAM tile units */')
    for k in ['BODY', 'TAIL_D', 'TAIL_L', 'TAIL_U', 'TAIL_R',
              'HEAD_U', 'HEAD_D', 'HEAD_L', 'HEAD_R', 'FOOD_A', 'FOOD_B',
              'BONUS_A', 'BONUS_B', 'SHARD_A', 'SHARD_B', 'FX_R1', 'FX_R2',
              'FX_R3', 'FX_R4', 'GATE', 'GATE_CORE']:
        lines.append('#define TID_%-14s %d' % (k, offs[k]))
    lines.append('')
    lines.append('#endif /* VSGFX_H */')
    lines.append('')

    with open(header_path, 'w') as f:
        f.write('\n'.join(lines))

    print("wrote %s and %d blob(s) in src/gfx/" % (header_path, len(blobs)))


if __name__ == '__main__':
    main()
